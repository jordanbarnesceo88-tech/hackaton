/**
 * Контракт имитации склада (lib/sim). Здесь только типы и версия модели — сам движок пишет
 * задача T1.3. Файл заморожен после волны W0: менять его может только оркестратор, а T1.3
 * вправе лишь ДОБАВЛЯТЬ поля (например, в `SimState`), не переименовывая существующие.
 *
 * Зачем отдельный контракт: экономика (lib/tz/econ) и имитация должны опираться на одну и ту
 * же геометрию склада (ТЗ §3.6.2 — визуализация подтверждает расчёт, а не украшает его), а
 * результат имитации хранится в проекте (`ProjectResults.sim`) и обязан воспроизводиться при
 * повторном открытии (ТЗ §3.1.5). Поэтому формы входа и сохраняемой сводки зафиксированы здесь.
 */

/**
 * Версия модели имитации. Входит в `ProjectResults.simModelVersion`: если при повторном
 * открытии проекта версия отличается, интерфейс показывает баннер «Пересчитать на актуальных
 * данных» вместо молчаливой подмены результата. Повышается при любом изменении логики
 * движка, которое меняет числа сводки.
 */
export const SIM_MODEL_VERSION = "sim-1.0.0" as const;

/**
 * Параметры объекта, из которых строится планировка. Это подмножество параметров склада
 * организатора (площадь активной зоны, ширина проездов) плюс наши дополнения (число ворот
 * приёмки и отгрузки) и число зарядных станций из расчёта экономики — чтобы схема на экране
 * была той же, по которой посчитано плечо перевозки.
 */
export type SimLayoutParams = {
  /** Площадь активной (роботизируемой) зоны, м². */
  activeAreaM2: number;
  /** Ширина главных (поперечных) проездов, м. */
  mainAisleWidthM: number;
  /** Ширина рабочих проходов между стеллажами, м. */
  rackAisleWidthM: number;
  /** Число ворот (точек) приёмки, шт. */
  receivingDocksCount: number;
  /** Число ворот (точек) отгрузки, шт. */
  shippingDocksCount: number;
  /** Число зарядных станций, шт. (C из расчёта экономики). */
  chargers: number;
};

/**
 * Точка выполнения операции: ворота приёмки, ворота отгрузки или зарядная станция. Каждая
 * обслуживает одного робота за раз — очередь у точки и есть узкое место «points».
 * Координаты в метрах от левого нижнего угла планировки.
 */
export type OpPoint = {
  id: string;
  kind: "receiving" | "shipping" | "charger";
  x: number;
  y: number;
};

/**
 * Построенная планировка склада: зоны, проезды, проходы, места хранения и точки операций.
 * Одна и та же структура рисуется в 2D-визуализации и используется в аналитическом расчёте
 * плеча (`analytic.expectedLegsM`), поэтому схема не может разойтись с экономикой.
 */
export type SimLayout = {
  /** Ширина планировки, м. */
  widthM: number;
  /** Глубина планировки, м. */
  heightM: number;
  /** Прямоугольники типовых зон (ТЗ §3.6.1) для отрисовки. Координаты и размеры в метрах. */
  zones: {
    kind: "receiving" | "storage" | "shipping" | "charging";
    label: string;
    x: number;
    y: number;
    w: number;
    h: number;
  }[];
  /** Координаты Y осей поперечных (главных) проездов, м. */
  crossAislesY: number[];
  /** Координаты X осей стеллажных проходов, м. */
  rackAislesX: number[];
  /** Места хранения (точки на осях стеллажных проходов), куда робот ставит и откуда забирает паллету. */
  slots: { x: number; y: number }[];
  receiving: OpPoint[];
  shipping: OpPoint[];
  chargers: OpPoint[];
};

/**
 * Характеристики парка, с которыми запускается имитация. Берутся из снимка продукта
 * (`ProductForCalc`) и нормативов; null означает «производитель не публикует» — движок тогда
 * не моделирует соответствующий эффект (например, зарядку) и сообщает об этом в выводе.
 */
export type RobotSimParams = {
  /** Число роботов в парке. */
  count: number;
  /** Паспортная скорость, м/с. */
  speedMps: number;
  /** Доля скорости при движении с грузом (норматив loadedSpeedFactor). */
  loadedSpeedFactor: number;
  /** Время захвата или постановки груза у точки, с (норматив по классу погрузки). */
  handlingSec: number;
  /** Автономность, ч; null — зарядка не моделируется. */
  autonomyH: number | null;
  /** Время зарядки, мин; null — зарядка не моделируется. */
  chargeMin: number | null;
  /** Грузоподъёмность, кг; null — предварительная проверка массы не выполняется. */
  payloadKg: number | null;
};

/**
 * Полный вход одного прогона. Детерминирован: одинаковый вход (включая `seed`) даёт
 * бит-в-бит одинаковую сводку в Node и в браузере — это условие воспроизводимости §3.1.5.
 */
export type SimInput = {
  /** Зерно генератора mulberry32. «Перезапуск» использует то же зерно. */
  seed: number;
  layout: SimLayoutParams;
  robots: RobotSimParams;
  /**
   * Поток заданий: сначала `warmupMin` минут на среднем потоке, затем `peakMin` минут на
   * пиковом. Метрики считаются только по пиковому окну.
   */
  demand: { avgPerH: number; peakPerH: number; warmupMin: number; peakMin: number };
  /** Масса перевозимой единицы, кг (средняя масса паллеты объекта); null — не проверяется. */
  loadMassKg: number | null;
  /** Пороги вердикта из нормативов simServedShareMin, simP95WaitMaxMin, simOversizedIdleShare. */
  thresholds: { servedShareMin: number; p95WaitMaxMin: number; oversizedIdleShare: number };
  /** Порог ухода на зарядку и возврата с неё, доли заряда (нормативы chargeStartSoc/chargeStopSoc). */
  charge: { startSoc: number; stopSoc: number };
};

/**
 * Состояние конечного автомата робота. Используется и движком, и визуализацией: форма и цвет
 * робота на схеме зависят от фазы (с грузом, пустой, на зарядке).
 */
export type RobotPhase =
  | "idle"
  | "toPickup"
  | "waitPoint"
  | "loading"
  | "toDrop"
  | "unloading"
  | "toCharger"
  | "waitCharger"
  | "charging";

/**
 * Итог проверки расчёта имитацией. CONFIRMED — парк держит пиковый поток по порогам;
 * NOT_CONFIRMED — не держит (узкое место указано в `SimBottleneck`); NOT_SUPPORTED — процесс
 * или продукт имитацией не моделируется (например, стационарная система), и это сказано
 * прямо, а не выдаётся за подтверждение.
 */
export type SimVerdict = "CONFIRMED" | "NOT_CONFIRMED" | "NOT_SUPPORTED";

/**
 * Что ограничивает пропускную способность: парк, точки приёмки/отгрузки, зарядка или
 * грузоподъёмность (робот не может везти груз объекта, прогон не выполняется).
 */
export type SimBottleneck = "none" | "fleet" | "points" | "charging" | "payload";

/**
 * Сводка имитации, которая сохраняется в проекте (`ProjectResults.sim`) и попадает в отчёт и
 * XLSX. Только скалярные поля — без временных рядов, чтобы результаты проекта оставались
 * компактными. Проценты — в процентах (0–100), доли — в долях (0–1).
 */
export type SimSummaryStored = {
  simModelVersion: string;
  seed: number;
  /** Ключ сценария (`ScenarioSpec.key`), для которого выполнен прогон. */
  scenarioKey: string;
  /** Число роботов в прогоне. */
  fleet: number;
  /** Требуемый пиковый поток, ед./ч (λpk из расчёта). */
  requiredPerH: number;
  /** Достигнутый поток за пиковое окно, ед./ч. */
  achievedPerH: number;
  /** Доля обслуженных за пик заданий, 0–1. */
  servedShare: number;
  /** Производительная загрузка парка по имитации, %. */
  fleetUtilPct: number;
  /** Загрузка, заложенная в расчёт (норматив utilization), % — для сравнения с fleetUtilPct. */
  assumedUtilPct: number;
  /** Доля времени простоя, %. */
  idlePct: number;
  /** Доля времени на зарядке (включая путь к станции и ожидание её), %. */
  chargingPct: number;
  /** Доля времени ожидания у занятых точек, %. */
  waitAtPointsPct: number;
  /** Максимальная длина очереди заданий. */
  queueMax: number;
  /** 95-й перцентиль ожидания задания, мин. */
  waitP95Min: number;
  verdict: SimVerdict;
  bottleneck: SimBottleneck;
  /** Простой не ниже порога simOversizedIdleShare — парк избыточен. */
  oversized: boolean;
  /** Минимальный устойчивый парк по перебору (null — не искали или не найден в диапазоне). */
  minStableFleet: number | null;
  /** Парк, рассчитанный по паспортной норме организатора (null — нормы нет). */
  fleetByNorm: number | null;
  /** Вердикт прогона с парком по норме организатора (null — не запускался). */
  verdictByNorm: "CONFIRMED" | "NOT_CONFIRMED" | null;
  /** Длительность прогона, мс (измеряет вызывающий код — движку часы запрещены). */
  durationMs: number;
};

/**
 * Полная сводка прогона: сохраняемые поля плюс ряды для графика и загрузка точек. Показывается
 * на экране имитации; в проект сохраняется только `SimSummaryStored`.
 */
export type SimSummary = SimSummaryStored & {
  /** Пятиминутные корзины пикового окна: требуемый и достигнутый поток, ед./ч. */
  buckets5min: { t: number; required: number; achieved: number }[];
  /** Загрузка каждой точки операций за пиковое окно, %. */
  pointUtilization: { id: string; kind: OpPoint["kind"]; utilPct: number }[];
  /**
   * Разложение времени парка по видам, % (в сумме 100): с грузом, порожний пробег,
   * погрузка/разгрузка, ожидание у точек, зарядка, простой.
   */
  shares: {
    loadedPct: number;
    emptyPct: number;
    handlingPct: number;
    waitAtPointsPct: number;
    chargingPct: number;
    idlePct: number;
  };
};

/**
 * Состояние движка имитации. Внутреннее устройство принадлежит T1.3: остальной код держит
 * значение как непрозрачное и передаёт его обратно в `stepSim`/`summarize`. Здесь объявлены
 * только поля, на которые может опираться визуализация; T1.3 расширяет интерфейс аддитивно.
 */
export interface SimState {
  /** Вход, с которым создан прогон (для «Перезапуска» с тем же зерном). */
  readonly input: SimInput;
  /** Модельное время с начала прогона, с. */
  tS: number;
}
