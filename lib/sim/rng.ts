/**
 * Сидируемый генератор случайных чисел для имитации склада.
 *
 * Имитация обязана давать бит-в-бит одинаковый результат в Node (расчёт при сохранении
 * проекта) и в браузере (проигрывание на экране), поэтому `Math.random` запрещён. mulberry32 —
 * 32-битный генератор на целочисленных операциях (`Math.imul`, сдвиги, xor): они определены
 * спецификацией ECMAScript точно и одинаково во всех движках.
 */

/**
 * Состояние генератора — одно 32-битное целое. Хранится в состоянии имитации как обычное
 * число, поэтому состояние прогона остаётся простыми данными: его можно сравнить в тесте и
 * скопировать без замыканий.
 */
export type RngState = { a: number };

/** Создаёт состояние генератора из зерна (приводится к 32-битному целому). */
export function createRng(seed: number): RngState {
  return { a: seed | 0 };
}

/**
 * Следующее число mulberry32 в [0, 1). Меняет `st` на месте. Алгоритм — общеизвестный
 * mulberry32 (Tommy Ettinger), тот же, что в прототипе scratchpad/simproto/proto.mjs.
 */
export function nextRandom(st: RngState): number {
  st.a = (st.a + 0x6d2b79f5) | 0;
  let t = Math.imul(st.a ^ (st.a >>> 15), 1 | st.a);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

/**
 * Генератор mulberry32 в виде функции без аргументов: каждый вызов — следующее число в
 * [0, 1). Одно и то же зерно всегда даёт одну и ту же последовательность.
 */
export function mulberry32(seed: number): () => number {
  const st = createRng(seed);
  return () => nextRandom(st);
}

/**
 * Доля шага, выше которой одно испытание Бернулли плохо приближает пуассоновский поток (два
 * задания за шаг становятся заметно вероятны). Выше порога шаг делится на под-испытания.
 */
const MAX_P_PER_DRAW = 0.1;

/**
 * Число заданий, поступивших за шаг `dtS` при интенсивности `ratePerS` заданий в секунду.
 *
 * Поток приближается испытаниями Бернулли, а не экспонентой между поступлениями: экспоненте
 * нужен логарифм, а он в разных движках может расходиться в последнем бите. Если λ·dt ≤ 0,1,
 * выполняется одно испытание с вероятностью λ·dt; иначе шаг делится на k = ⌈λ·dt / 0,1⌉
 * под-испытаний с вероятностью λ·dt / k каждое. Математическое ожидание в обоих случаях
 * ровно λ·dt. Нулевая или отрицательная интенсивность генератор не трогает.
 */
export function bernoulliArrivals(rng: () => number, ratePerS: number, dtS = 1): number {
  const p = ratePerS * dtS;
  if (!(p > 0) || !Number.isFinite(p)) return 0;
  const k = p > MAX_P_PER_DRAW ? Math.ceil(p / MAX_P_PER_DRAW) : 1;
  const q = p / k;
  let n = 0;
  for (let i = 0; i < k; i++) {
    if (rng() < q) n++;
  }
  return n;
}
