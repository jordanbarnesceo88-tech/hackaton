/**
 * Словарь терминов, которыми продукт разговаривает с человеком.
 *
 * Заведён потому, что объяснения были, но добраться до них можно было только через расчёт:
 * `EXPLANATIONS` живут у чисел на панели, `ASSUMPTION_JUSTIFICATIONS` — у полей допущений, а
 * оба экрана открываются в конце мастера. До них человек успевает прочитать AS/RS, AMR, ЭПЗ,
 * CAPEX и «покрытие» — и ни одно из этих слов нигде не расшифровано. Аудитория не обязана
 * знать вокабуляр складской автоматизации, а тот, кто не знает одного термина, не может
 * оценить экран, на котором он стоит: он не спорит с цифрой, он её пролистывает.
 *
 * Правило, из-за которого этот файл опаснее, чем кажется: термины, которые ЭТОТ продукт
 * считает (NPV, дисконтированная окупаемость, ЭПЗ, покрытие, замещение труда, CAPEX, OPEX),
 * описываются так, как их определяет движок, а не так, как их определяет учебник. Словарь,
 * разошедшийся с `calculate.ts`, хуже отсутствующего: он даёт скептику готовое возражение
 * («у вас написано одно, а посчитано другое») ровно там, где продукт обещает защищаемость.
 * Поэтому каждое такое определение сверено с `lib/economics/` — и при правке движка правится
 * вместе с ним.
 *
 * Чего здесь нет и быть не может: источников, статистики и цитат. Словарь объясняет слова,
 * а не утверждает факты о мире — утверждения о мире живут в `lib/sources/` с ссылкой и датой
 * проверки. Ни одно определение отсюда не должно выглядеть как данные.
 */

