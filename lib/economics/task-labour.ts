export type TaskLabourInput = {
  /** Сколько человек, по словам владельца объекта, занято этой задачей. */
  declared: number | undefined;
  /** Годовой объём работы ЭТОЙ задачи — из `demandPerYear` по потоку категории. */
  demandPerYear: number;
  /** Норматив выработки человека. `null` — норматива со ссылкой у категории нет. */
  workerOutputPerYear: number | null;
  /** Весь штат объекта — жёсткий потолок. */
  staffCount: number;
};

/**
 * Сколько человек заняты задачей — единственное место, где этот вопрос решается.
 *
 * Появилась потому, что предел замещения выводился из спроса через ОДНО глобальное число на
 * все задачи: `opsPerWorkerPerYear = 12 500`, то есть 6 операций в час. Отраслевой бенчмарк по
 * отбору заказов — 80–120 в час, по укладке коробок — 200–400; допущение занижено в 13–50 раз,
 * и всегда в сторону завышения замещаемого персонала. На пищевом производстве это давало «один
 * паллетайзер за $12 143 замещает весь штат комбината» и окупаемость в одиннадцать дней.
 *
 * Порядок источников: заявленное человеком → норматив → null. Владелец объекта знает свою
 * занятость точнее любого источника, поэтому его ответ первичен, а норматив служит
 * предзаполнением, которое видно на экране и которое можно поправить.
 *
 * `null` — это НЕ ноль. Ноль означает «этой задачей никто не занят, экономить нечего»; `null`
 * означает «мы не знаем», и вызывающий обязан отказаться считать. Слить их значило бы показать
 * ноль экономии там, где ответа просто нет, — то есть утверждать то, чего мы не знаем.
 *
 * Тотальна для любого конечного входа: ни Infinity, ни NaN наружу не выходят.
 */
export function resolveTaskFte(input: TaskLabourInput): number | null {
  const { declared, demandPerYear, workerOutputPerYear, staffCount } = input;

  // Потолок штата. Нефинитный или отрицательный штат — это не «без потолка», а испорченный
  // ввод: нулевой потолок честнее, чем неограниченное замещение по мусорному числу.
  const cap = Number.isFinite(staffCount) && staffCount > 0 ? staffCount : 0;

  // Негодное заявленное значение не переносится и не «чинится» — расчёт откатывается к
  // нормативу, как это делают переопределения количества и цены.
  if (typeof declared === "number" && Number.isFinite(declared) && declared >= 0) {
    return Math.min(cap, declared);
  }

  if (workerOutputPerYear === null || !(workerOutputPerYear > 0)) return null;
  // NaN спроса — это «неизвестно», и считать по нему нельзя. Отрицательный спрос — это «работы
  // нет», а не «неизвестно»: он зажимается в ноль, и решение честно доходит до «нет экономии»
  // с нулём замещённых вместо голого отказа. Различие не косметическое: null здесь означал бы,
  // что человеку нечего исправлять, хотя исправлять надо отрицательное число операций.
  if (!Number.isFinite(demandPerYear)) return null;
  if (demandPerYear < 0) return 0;
  return Math.min(cap, demandPerYear / workerOutputPerYear);
}
