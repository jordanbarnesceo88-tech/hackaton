import type { AssumptionValues, FacilityParams, SolutionCapacity } from "./types";
import { capacityPerYear, demandPerYear } from "./normalize";

/**
 * Единица производительности решения НЕ сопоставима с «операцией объекта» — и это видно в
 * результате.
 *
 * Поток развёл уборку и отбор заказов (`workloadStream`), но внутри потока операций остались
 * восемь разных единиц: отборов/час, коробок/час, посылок/час, тотов/час, деталей/час,
 * циклов/час, презентаций/час, доставок/сутки. Движок сравнивает любую из них с одним
 * `opsPerDay`, потому что `capacityUnit` — свободная строка, которую он не читает вовсе
 * (проверено: она встречается только в отображении).
 *
 * Это тот же класс ошибки, который проект уже однажды исправил — «5000 отборов заказов в сутки
 * сопоставлялись с 2780 м² уборки в час как одна и та же величина», — и исправление
 * остановилось на уровень выше нужного.
 *
 * Исправить модель до конкурса нельзя: это спека, а не правка, и она меняет каждое число на
 * каждом типе объекта. Но молчать нельзя тем более. Измерено по каталогу (137 пар «тип объекта
 * × решение»): сервисному роботу доставки на складе нужно 108 машин, а одна станция ИИ-инспекции
 * «закрывает» объект, работы которого в 656 раз больше её годовой производительности.
 *
 * Поэтому здесь не исправление, а ЧЕСТНОЕ ИМЯ: там, где несоизмеримость видна в ответе,
 * результат помечается как несопоставимый, и названа настоящая причина.
 *
 * Пороги — эвристика отображения, а не факт о мире, и подобраны по измерению: у всех решений,
 * чья единица действительно сопоставима с операцией объекта, парк укладывается в единицы машин,
 * а покрытие одной машиной не превышает спрос на порядок. Пороги намеренно щедрые: ложное
 * предупреждение на нормальном решении дороже пропущенного на абсурдном.
 */
export const IMPLAUSIBLE_FLEET = 25;
export const OVER_COVERAGE_RATIO = 20;

export type UnitMismatch =
  /** Парк в десятки машин: единица решения много мельче операции объекта. */
  | { kind: "fleet"; quantity: number }
  /** Одна машина «закрывает» объект многократно: единица решения много крупнее операции. */
  | { kind: "coverage"; ratio: number };

/**
 * Заметна ли несоизмеримость в этом конкретном ответе. `null` — не заметна; это НЕ значит,
 * что единицы сопоставимы, только что расхождение не бросается в глаза.
 */
export function detectUnitMismatch(
  cap: SolutionCapacity,
  params: FacilityParams,
  a: AssumptionValues,
  quantity: number
): UnitMismatch | null {
  // Поток площади сравнивает м² с м² — там единица одна и та же по построению.
  if (cap.workloadStream !== "OPERATION_FLOW") return null;
  if (!Number.isFinite(quantity)) return null;

  if (quantity >= IMPLAUSIBLE_FLEET) return { kind: "fleet", quantity };

  const perYear = capacityPerYear(cap, a);
  const demand = demandPerYear(params, a, cap.workloadStream);
  if (!(perYear > 0) || !(demand > 0)) return null;
  const ratio = perYear / demand;
  if (quantity === 1 && ratio >= OVER_COVERAGE_RATIO) return { kind: "coverage", ratio };

  return null;
}
