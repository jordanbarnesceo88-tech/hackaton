import type { AssumptionValues } from "./types";

/**
 * Обоснование каждого допущения — почему именно это число.
 *
 * Самый большой разрыв между тем, что продукт обещает, и тем, что показывает: `/methodology`
 * рассказывает, как мы не даём себе соврать, а у 15 из 16 допущений обоснование было пустым.
 * Каждое из этих чисел участвует в КАЖДОМ расчёте и редактируется на экране, поэтому вопрос
 * «почему 15 % на монтаж?» — первый, который задаст скептик, и до сих пор он оставался без
 * ответа.
 *
 * Реестр типизирован по `keyof AssumptionValues`, поэтому допущение без обоснования **не
 * компилируется**. Это то же правило, что у `EXPLANATIONS`: одно необъяснимое число
 * компрометирует остальные.
 *
 * `basis` обязателен и важнее текста. Не все шестнадцать имеют источник, и делать вид, что
 * имеют, нельзя: `roiHorizonYears` и `discountRate` — это выбор владельца, а не факт о мире.
 * Тогда так и пишется. Пустота недопустима, выдуманная ссылка — тем более.
 */
export type JustificationBasis =
  /**
   * Опирается на опубликованный источник. Либо `sourceUrl`, либо — когда источников
   * несколько и из них сделан наш вывод — текст обязан назвать, где лежит полная
   * арифметика (`docs/data-provenance.md`). Проверяется тестом.
   */
  | "источник"
  /** Наша оценка порядка величины. Источника нет, и это сказано вслух. */
  | "оценка"
  /** Решение владельца модели, а не факт о мире. Спорить с ним можно, проверить — нельзя. */
  | "наш выбор"
  /** Арифметика из других допущений или соглашение об учёте. */
  | "соглашение";

export type Justification = {
  basis: JustificationBasis;
  text: string;
  sourceUrl?: string;
};

