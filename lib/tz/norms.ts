/** Ключ норматива. Выводится из NORM_DEFS, поэтому опечатка в движке не компилируется. */
export type NormKey = (typeof NORM_DEFS)[number]["key"];

/** Полный набор значений нормативов, с которым выполнен расчёт (сохраняется в проекте). */
export type NormValues = Record<NormKey, number>;

const DEF_BY_KEY: ReadonlyMap<string, NormDef> = new Map(NORM_DEFS.map((d) => [d.key, d]));

/** Проверяет, что строка — известный ключ норматива (для строк из БД и API). */
export function isNormKey(key: string): key is NormKey {
  return DEF_BY_KEY.has(key);
}

/** Описание норматива по ключу: подпись, единица, происхождение, обоснование. */
export function normDef(key: NormKey): NormDef {
  const def = DEF_BY_KEY.get(key);
  // Недостижимо при типизированном ключе; проверка защищает от строк, приведённых через `as`.
  if (!def) throw new Error(`Неизвестный норматив: ${key}`);
  return def;
}

/**
 * Значения нормативов по умолчанию (из кода). Заморожены: расчёт получает копию через
 * `resolveNorms`, и случайная мутация одного проекта не может изменить умолчания для другого.
 */
export const DEFAULT_NORMS: Readonly<NormValues> = Object.freeze(
  Object.fromEntries(NORM_DEFS.map((d) => [d.key, d.value])) as NormValues,
);

/** Прижимает значение к [min, max] норматива; null-граница не ограничивает. */
function clampToDef(def: NormDef, value: number): number {
  let v = value;
  if (def.min !== null && v < def.min) v = def.min;
  if (def.max !== null && v > def.max) v = def.max;
  return v;
}

/**
 * Минимальный зазор между порогом ухода на зарядку и порогом возврата в работу, доля заряда.
 * Меньший зазор заставил бы робота метаться между работой и зарядкой; 5 п.п. — наш выбор,
 * он же задаёт границы chargeStartSoc ≤ 0,95 и chargeStopSoc ≥ 0,05.
 */
export const CHARGE_SOC_MIN_GAP = 0.05;

/** Ключи весов балла подбора: после правок они нормируются так, чтобы сумма была равна 1. */
export const SCORE_WEIGHT_KEYS = [
  "scoreWeightEcon",
  "scoreWeightData",
  "scoreWeightMaturity",
  "scoreWeightMargin",
  "scoreWeightCases",
] as const satisfies readonly NormKey[];

/**
 * Допуск, в пределах которого сумма весов считается равной 1. Сумма умолчаний в двоичной
 * арифметике равна 1,0000000000000002; без допуска деление на неё сдвинуло бы веса по
 * умолчанию в последнем знаке и изменило бы хэш версии данных.
 */
const WEIGHT_SUM_TOLERANCE = 1e-9;

/** Убирает хвост двоичной арифметики (0,1 + 0,05 = 0,15000000000000002). */
function roundShare(v: number): number {
  return Math.round(v * 1e9) / 1e9;
}

/**
 * Восстанавливает взаимные ограничения, которые не выразить границами одного норматива
 * (см. комментарий к модулю). Меняет `out` на месте; при значениях по умолчанию ничего не
 * меняет.
 */
function enforceCrossConstraints(out: NormValues): void {
  // Интервалы окупаемости не переворачиваются: «долгая» граница не ниже «быстрой».
  if (out.paybackBandSlowYears < out.paybackBandFastYears) {
    out.paybackBandSlowYears = out.paybackBandFastYears;
  }

  // Порог возврата в работу выше порога ухода на зарядку минимум на CHARGE_SOC_MIN_GAP.
  const minStop = roundShare(out.chargeStartSoc + CHARGE_SOC_MIN_GAP);
  if (out.chargeStopSoc < minStop) out.chargeStopSoc = Math.min(1, minStop);

  // Веса балла подбора в сумме дают 1, чтобы балл оставался в пределах 0–100.
  const sum = SCORE_WEIGHT_KEYS.reduce((acc, key) => acc + out[key], 0);
  if (sum <= 0) {
    for (const key of SCORE_WEIGHT_KEYS) out[key] = DEFAULT_NORMS[key];
  } else if (Math.abs(sum - 1) > WEIGHT_SUM_TOLERANCE) {
    for (const key of SCORE_WEIGHT_KEYS) out[key] = out[key] / sum;
  }
}

/**
 * Итоговые нормативы расчёта: код → строки таблицы Norm (правки администратора) →
 * переопределения сценария или пользователя. Каждое значение прижимается к [min, max]
 * своего норматива, неизвестные ключи и нечисловые значения (NaN, ±∞) игнорируются — так
 * испорченная строка в БД не может сломать расчёт или вывести его за допустимые границы.
 *
 * После этого восстанавливаются взаимные ограничения: «долгая» граница окупаемости не ниже
 * «быстрой», порог возврата с зарядки не ниже порога ухода + 5 п.п., веса балла подбора
 * нормируются к сумме 1 (при нулевой сумме — веса по умолчанию). Потребители (подбор T1.4,
 * имитация T1.3, интерпретация окупаемости) получают уже согласованные значения и сами их
 * не исправляют.
 */
export function resolveNorms(
  rows?: readonly { key: string; value: number }[],
  overrides?: Partial<NormValues>,
): NormValues {
  const out = { ...DEFAULT_NORMS } as NormValues;
  const apply = (key: string, value: unknown) => {
    const def = DEF_BY_KEY.get(key);
    if (!def || typeof value !== "number" || !Number.isFinite(value)) return;
    out[key as NormKey] = clampToDef(def, value);
  };
  for (const row of rows ?? []) apply(row.key, row.value);
  for (const [key, value] of Object.entries(overrides ?? {})) apply(key, value);
  enforceCrossConstraints(out);
  return out;
}
