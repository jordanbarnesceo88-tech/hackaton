import type { Origin } from "./types";

/**
 * Нормативы модели tz-1.0.0 — все числа, которые участвуют в расчёте, но не являются
 * параметрами объекта. ТЗ §3.5.1 запрещает недокументированные коэффициенты, а §3.5.8 требует
 * показывать источники и допущения, поэтому у каждого норматива есть происхождение (`origin`),
 * обоснование (`basis`) и, где он есть, источник (`sourceRef`/`sourceUrl`) или формула.
 *
 * Правила (проверяются тестом norms.test.ts):
 * - organizer и tz — обязателен `sourceRef` (где именно у организатора или в ТЗ);
 * - research — https-ссылка `sourceUrl` или отсылка к docs/data-provenance.md в `basis`;
 * - estimate, derived, choice — `basis` не короче 40 символов: оценка обязана сказать, на чём
 *   она держится, а выбор — что это выбор, а не факт;
 * - derived — обязательна `formula`;
 * - значение по умолчанию лежит в [min, max].
 *
 * Значения из таблицы Norm (правит администратор) перекрывают эти, но не выходят за [min, max]
 * — см. `resolveNorms`. Если у норматива нет содержательного диапазона, задана естественная
 * граница (величина неотрицательна, доля не больше 1), а не выдуманный интервал.
 *
 * Границы проверяют каждый норматив по отдельности, поэтому `resolveNorms` после них
 * восстанавливает и взаимные ограничения (проверяются тестом):
 * - paybackBandSlowYears ≥ paybackBandFastYears — интервалы окупаемости не переворачиваются;
 * - chargeStopSoc ≥ chargeStartSoc + 0,05 — робот не мечется между работой и зарядкой;
 * - веса балла подбора scoreWeight* в сумме дают 1 — при другой сумме каждый вес делится на
 *   сумму, при нулевой сумме берутся веса по умолчанию. Подбор (T1.4) берёт веса из
 *   `NormValues` и сам их не нормирует.
 */

/** Происхождение норматива: подмножество `Origin` без правок администратора и пользователя. */
export type NormOrigin = Extract<Origin, "organizer" | "research" | "estimate" | "derived" | "choice" | "tz">;

/** Группа норматива — раздел на странице методики и в админке «Нормативы». */
export type NormGroup =
  | "Режим и загрузка"
  | "Труд"
  | "CAPEX"
  | "OPEX"
  | "Финансы"
  | "Интерпретация"
  | "Имитация"
  | "Подбор";

/**
 * Описание одного норматива. Та же форма засевается в таблицу Norm (T2.1) и выводится на
 * /methodology/tz и в отчёте, поэтому поля совпадают с колонками таблицы.
 */
export type NormDef = {
  key: string;
  /** Название для людей, на русском. */
  label: string;
  /** Значение по умолчанию. */
  value: number;
  /** Нижняя граница допустимого значения; null — без границы. */
  min: number | null;
  /** Верхняя граница допустимого значения; null — без границы. */
  max: number | null;
  unit: string;
  origin: NormOrigin;
  group: NormGroup;
  /** Почему именно это число. Для оценки — на чём держится, для выбора — что это выбор. */
  basis: string;
  /** Где именно у организатора, в ТЗ или у производителя. */
  sourceRef?: string;
  /** Ссылка на открытый источник (для research). */
  sourceUrl?: string;
  /** Формула вывода (для derived). */
  formula?: string;
  /** Порядок показа внутри группы. */
  order: number;
};

