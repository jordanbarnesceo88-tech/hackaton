/**
 * Замер длительности расчёта для строки состояния (ТЗ §4.3.3: экономический расчёт не дольше
 * 10 с с видимым статусом). Часы передаёт вызывающий код — в браузере `performance.now`, на
 * сервере `performance.now` или `Date.now`: модуль не читает часы сам, поэтому остаётся чистой
 * функцией и не нарушает правило чистоты рендера (его вызывают из обработчиков событий и
 * обычных функций, а не из тела компонента).
 */

/** Результат функции и время её выполнения, мс. */
export type Timed<T> = { value: T; ms: number };

/**
 * Выполняет `fn` и измеряет время часами `now`. Отрицательная разница (часы ушли назад) и
 * нечисловое значение дают 0 мс, а не «−3 мс» в строке состояния.
 */
export function timed<T>(fn: () => T, now: () => number): Timed<T> {
  const t0 = now();
  const value = fn();
  const dt = now() - t0;
  return { value, ms: Number.isFinite(dt) && dt > 0 ? dt : 0 };
}
