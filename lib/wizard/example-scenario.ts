import { buildWizardQuery } from "./steps";
import type { FacilityParams } from "@/lib/economics/types";

/**
 * Готовый пример — путь к посчитанным числам без единого набранного символа.
 *
 * Самая окупаемая вещь из разбора конкурса: человек, смотрящий двадцать проектов подряд, не
 * будет заполнять шесть шагов, чтобы узнать, о чём продукт. До этого ни одного пути «посмотреть
 * на готовом» не существовало — первый экран вёл в опрос, опрос требовал ответов.
 *
 * Числа НЕ подобраны так, чтобы всё окупалось. На этих параметрах из шести решений склада
 * годным оказывается одно — робот-уборщик, окупаемость 1,14 года, — а пять остальных не
 * возвращают вложения внутри горизонта. Это и есть демонстрация: инструмент, который отвечает
 * «нет» пяти раз из шести, убедительнее инструмента, который всегда говорит «да». Пример,
 * подобранный под сплошной успех, первым же вопросом («а когда не окупается?») и обрушился бы.
 *
 * Занятость по задачам заполнена так же, как её заполнил бы владелец: где у задачи есть
 * норматив со ссылкой — округлённый норматив (отбор 6, уборка 4), где норматива нет —
 * правдоподобное число. Сумма 28 из 40 человек: остальные 12 не роботизируются, и экран это
 * говорит вслух.
 */
export const EXAMPLE_FACILITY = "warehouse";
export const EXAMPLE_INDUSTRY = "retail";
export const EXAMPLE_OBJECT_NAME = "Распределительный центр, 10 000 м²";

export const EXAMPLE_PARAMS: FacilityParams = {
  areaM2: 10000,
  opsPerDay: 5000,
  staffCount: 40,
  taskStaffing: {
    asrs: 8,
    amr: 6,
    "class-amr-transport": 6,
    "class-palletizer": 4,
    "class-cleaning": 4,
  },
};

/** Ссылка на экран сравнения с полностью заполненным состоянием подбора. */
export function exampleHref(): string {
  return `/compare/${EXAMPLE_FACILITY}?${buildWizardQuery({
    industry: EXAMPLE_INDUSTRY,
    facility: EXAMPLE_FACILITY,
    objectName: EXAMPLE_OBJECT_NAME,
    params: EXAMPLE_PARAMS,
  })}`;
}
