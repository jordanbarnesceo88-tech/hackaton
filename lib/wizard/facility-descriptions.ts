/**
 * Описание каждого типа объекта: что это за объект и какую работу здесь автоматизируют первой.
 *
 * До этого модуля сорок семь типов объектов были сорока семью голыми названиями. Человек,
 * листающий справочник, видел список ярлыков — «Даркстор», «Элеватор», «Чистое помещение» —
 * и не имел ни одного основания решить, что за ними стоит хоть какая-то предметная глубина.
 * Хуже того, выбор типа объекта определяет и типовые параметры, и набор применимых решений:
 * ошибиться на этом шаге дороже, чем на любом следующем, а подсказки не было никакой.
 *
 * ЗДЕСЬ НЕТ НИ ОДНОЙ ЦИФРЫ, и это правило, а не случайность. В продукте каждое число обязано
 * иметь источник и дату проверки; описание типа объекта источником не является и стать им не
 * может. Написанные тут «в среднем столько-то процентов» или «рынок таких объектов такой-то»
 * выглядели бы как данные, проверить их было бы нечем, и одно такое предложение обесценило бы
 * ссылки, расставленные у настоящих чисел. Числа объекта человек вводит сам на следующем шаге,
 * ориентир для них живёт в TYPICAL_PARAMS. Запрет проверяется тестом.
 *
 * `firstAutomated` не выдумывается: он пересказывает словами то, что уже записано в
 * applicability.ts — порядок категорий в этом массиве и есть порядок показа решений на экране
 * объекта. Описание, обещающее одно, а показывающее другое, хуже отсутствующего.
 *
 * Реестр НЕ импортирует таксономию: он живёт в клиентском коде шага, а посевные данные — в
 * scripts/. Связь между ними держит тест: он и только он гарантирует, что описан каждый slug и
 * что ни одно описание не осиротело после переименования типа. Тип этого не умеет — список
 * типов объектов существует в рантайме, а не в системе типов.
 */
export type FacilityDescription = {
  /** Что это за объект: один-два конкретных предложения. Не «объект для хранения товаров». */
  what: string;
  /** Какую работу здесь автоматизируют первой — в терминах работы, а не техники. */
  firstAutomated: string;
};

