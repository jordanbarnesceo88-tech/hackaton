-- М-2: стабильный `slug` у решения.
--
-- Личность решения была парой (категория, имя): upsert сева шёл по
-- `solutionCategoryId_name`. Переименование в источнике заводило ВТОРУЮ строку, старую держал
-- живой сохранённый расчёт (FK Restrict), обновлять её было больше некому — и её цена
-- застывала на дате последнего сева, знавшего старое имя. Смена категории делала то же самое.
--
-- Порядок шагов ниже — единственный возможный на живой таблице: NOT NULL требует значения для
-- каждой существующей строки, значит сначала nullable, потом бэкфилл, и только потом
-- ограничения.

-- 1. Колонка. Пока nullable.
ALTER TABLE "Solution" ADD COLUMN "slug" TEXT;

-- 2. Бэкфилл по парам (категория, имя), известным источникам сева НА МОМЕНТ ЭТОГО КОММИТА.
--
--    ЭТОТ СПИСОК НЕ РЕДАКТИРУЕТСЯ НИКОГДА. Он описывает ИСТОРИЮ — то, что источники объявляли
--    в день применения миграции, — а не текущее их содержимое. Источники после этого свободно
--    переименовывают решения и переносят их между категориями: в том и смысл slug'а. Если
--    подправить список вслед за источником, миграция начнёт означать не то, что она сделала на
--    базах, где уже применена, и две базы разъедутся молча. Новые решения slug получают в
--    источнике сева, а не здесь.
UPDATE "Solution" s SET "slug" = v.slug
FROM (VALUES
  ('class-amr-transport',   'AMR: транспортировка и подбор (класс)', 'class-amr-transport'),
  ('class-palletizer',      'Робот-паллетайзер (класс)',             'class-palletizer'),
  ('class-sorter',          'Сортировочный робот (класс)',           'class-sorter'),
  ('class-cleaning',        'Робот-уборщик промышленный (класс)',    'class-cleaning'),
  ('class-cobot-pickplace', 'Кобот: pick-and-place (класс)',         'class-cobot-pickplace'),
  ('class-service-delivery','Сервисный робот доставки (класс)',      'class-service-delivery'),
  ('class-ai-inspection',   'ИИ-инспекция качества (класс)',         'class-ai-inspection'),
  ('class-cleaning',        'Gausium Scrubber 75',                   'gausium-scrubber-75'),
  ('amr',                   'HaiPick A42T',                          'haipick-a42t'),
  ('asrs',                  'Exotec Skypod (станция)',               'exotec-skypod-station'),
  ('asrs',                  'AutoStore (порт)',                      'autostore-port')
) AS v(cat, nm, slug), "SolutionCategory" sc
WHERE sc.id = s."solutionCategoryId" AND sc.slug = v.cat AND s.name = v.nm;

-- 3. Всё остальное — строки организатора, уже переименованные до появления slug'а, заглушки
--    старых выкатов — получает заведомо неканонический, но стабильный и уникальный slug.
--    Префикс виден глазом: `legacy-` в каталоге означает «эту строку не обновляет ни один
--    источник сева». Строку без ссылок чистка сева удалит на первом же прогоне; строку со
--    ссылками — оставит, и слить её с канонической придётся руками (docs/DEPLOY.md, Б.4).
UPDATE "Solution" SET "slug" = 'legacy-' || "id" WHERE "slug" IS NULL;

-- 4. Теперь ограничения: каждая строка значение имеет, и оно уникально.
ALTER TABLE "Solution" ALTER COLUMN "slug" SET NOT NULL;
CREATE UNIQUE INDEX "Solution_slug_key" ON "Solution"("slug");
