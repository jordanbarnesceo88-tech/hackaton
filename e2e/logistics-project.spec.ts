import { test, expect } from "@playwright/test";
import ExcelJS from "exceljs";
import { PrismaClient } from "@prisma/client";
import { PrismaPg } from "@prisma/adapter-pg";
import { businessExampleInputs } from "../lib/projects/business-examples";
import { baseValuesFor } from "../lib/data/organizer/params";
import { CATALOG } from "../lib/data/organizer/catalog";
import { productForCalcFromSeed } from "../lib/catalog/product-for-calc";

test("deployment delivery survives actual UI calculation, worker SAVE, reopening and report exports", async ({ page }, testInfo) => {
  test.setTimeout(240_000);
  page.setDefaultTimeout(15_000);
  const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }) });
  const jobIds: string[] = [];
  let projectId: string | undefined;
  const logistics = { mode: "separate", costRub: 234567, source: "КП E2E LOG-42: весь парк, НДС и страховка" };
  try {
    await page.goto("/login");
    await page.locator("#email").fill("demo@demo.local");
    await page.locator("#password").fill(process.env.DEMO_USER_PASSWORD ?? "demo-user-2026");
    await page.getByRole("button", { name: "Войти", exact: true }).click();
    await expect(page).toHaveURL(/\/projects$/);
    const input = businessExampleInputs("steady-flow", baseValuesFor("warehouse"), CATALOG.map(productForCalcFromSeed));
    const create = await page.request.post("/api/v1/calculation-jobs", { data: { operation: "CREATE", name: `e2e-logistics-${Date.now()}`, facility: "warehouse", params: input.params, scenarios: input.scenarios }, headers: { "Idempotency-Key": crypto.randomUUID() } });
    expect(create.status(), await create.text()).toBe(202);
    const createId = (await create.json()).job.id as string; jobIds.push(createId);
    await expect.poll(async () => (await (await page.request.get(`/api/v1/calculation-jobs/${createId}`)).json()).job.status, { timeout: 90_000 }).toBe("SUCCEEDED");
    projectId = (await (await page.request.get(`/api/v1/calculation-jobs/${createId}/result`)).json()).job.projectId;
    const before = await db.project.findUniqueOrThrow({ where: { id: projectId }, select: { revision: true, results: true } });
    await page.goto(`/projects/${projectId}?edit=1#economics`);
    await page.locator("#economics").getByRole("tab", { name: "Покупка — Ronavi H1500", exact: true }).click();
    let region = page.getByRole("region", { name: "Доставка полного внедрения", exact: true });
    await expect(region).toContainText("не оценена");
    await region.getByText("Уточнить условия доставки", { exact: true }).click();
    await region.getByRole("combobox", { name: "Учёт доставки", exact: true }).selectOption("separate");
    await region.getByLabel("Доставка всего сценария с НДС, ₽", { exact: true }).fill(String(logistics.costRub));
    await region.getByLabel("Источник и состав поставки", { exact: true }).fill(logistics.source);
    const accepted = page.waitForResponse(r => r.url().endsWith("/api/v1/calculation-jobs") && r.request().method() === "POST");
    await region.getByRole("button", { name: "Применить и пересчитать", exact: true }).click();
    const calculation = await accepted;
    expect(calculation.status(), await calculation.text()).toBe(202);
    expect(calculation.request().postDataJSON().scenarios.find((s: { key: string }) => s.key === "purchase").logistics).toEqual(logistics);
    jobIds.push((await calculation.json()).job.id);
    await expect(page.locator("[data-server-calculation]")).toHaveAttribute("data-server-calculation", "ready", { timeout: 90_000 });
    await page.getByRole("navigation", { name: "Шаги расчёта" }).getByRole("link", { name: /^8 / }).click();
    const savedResponse = page.waitForResponse(r => r.url().endsWith("/api/v1/calculation-jobs") && r.request().method() === "POST");
    await page.getByRole("button", { name: "Сохранить проект", exact: true }).click();
    const save = await savedResponse; expect(save.status(), await save.text()).toBe(202); jobIds.push((await save.json()).job.id);
    await expect(page.getByText(/^Проект сохранён/)).toBeVisible({ timeout: 90_000 });
    const saved = await db.project.findUniqueOrThrow({ where: { id: projectId }, select: { revision: true, results: true } });
    const result = saved.results as unknown as { scenarios: { key: string; logistics?: unknown }[]; results: { key: string; capexRub: number; npvRub: number }[] };
    expect(saved.revision).toBe(before.revision + 1);
    expect(result.scenarios.find(s => s.key === "purchase")?.logistics).toEqual(logistics);
    const prior = (before.results as unknown as typeof result).results.find(r => r.key === "purchase")!;
    const after = result.results.find(r => r.key === "purchase")!;
    expect(after.capexRub - prior.capexRub).toBeCloseTo(logistics.costRub * 1.1, 2);
    expect(after.npvRub - prior.npvRub).toBeCloseTo(-logistics.costRub * 1.1, 2);
    const journal = await db.changeLog.findMany({ where: { projectId, field: "scenario:logistics" } });
    expect(journal).toHaveLength(1); expect(journal[0]!.newValue).toEqual(logistics);
    await page.goto(`/projects/${projectId}#economics`);
    await page.locator("#economics").getByRole("tab", { name: "Покупка — Ronavi H1500", exact: true }).click();
    region = page.getByRole("region", { name: "Доставка полного внедрения", exact: true });
    await expect(region).toContainText(logistics.source); await expect(region.locator("form")).toHaveCount(0);
    await page.goto(`/projects/${projectId}/report?scenario=purchase`);
    await expect(page.locator("body")).toContainText(logistics.source);
    await expect(page.locator("body")).toContainText("Доставка полного внедрения");
    const csv = await page.request.get(`/projects/${projectId}/export.csv`);
    expect(csv.status()).toBe(200);
    expect(await csv.text()).toContain(logistics.source);
    const xlsx = await page.request.get(`/projects/${projectId}/export.xlsx`);
    expect(xlsx.status()).toBe(200);
    const bytes = await xlsx.body(), buffer = new ArrayBuffer(bytes.byteLength);
    new Uint8Array(buffer).set(bytes);
    const workbook = new ExcelJS.Workbook(); await workbook.xlsx.load(buffer);
    const capex = workbook.worksheets.find(sheet => sheet.name.includes("CAPEX"));
    const delivery: ExcelJS.Row[] = [];
    capex!.eachRow(row => { if (JSON.stringify(row.values).includes(logistics.source)) delivery.push(row); });
    expect(delivery).toHaveLength(1); expect(JSON.stringify(delivery[0]!.values)).toContain("234567");
    await testInfo.attach("actual-logistics-save", { body: JSON.stringify({ projectId, jobIds, revision: saved.revision, logistics, deltaCapexRub: after.capexRub - prior.capexRub, deltaNpvRub: after.npvRub - prior.npvRub }), contentType: "application/json" });
  } finally {
    if (projectId) await db.project.deleteMany({ where: { id: projectId, name: { startsWith: "e2e-logistics-" } } });
    const jobs = await db.calculationJob.findMany({ where: { id: { in: jobIds }, status: { in: ["SUCCEEDED", "FAILED", "CANCELLED"] } }, select: { runId: true } });
    await db.calculationRun.deleteMany({ where: { id: { in: jobs.map(j => j.runId) } } });
    await db.$disconnect();
  }
});
